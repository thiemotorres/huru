#!/usr/bin/env python3
"""Generates the Ko-fi QR code as an Android vector drawable (no QR library in the app).

Usage: pip install segno && python3 tools/kofi_qr.py
Output: app/src/main/res/drawable/kofi_qr.xml
"""
import os, re, io
import segno

URL = "https://ko-fi.com/thiemotorres"
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable", "kofi_qr.xml")

qr = segno.make(URL, error="m")
buf = io.BytesIO()
qr.save(buf, kind="svg", border=2, xmldecl=False, svgns=False)  # one stroked path, 1 unit per module
svg = buf.getvalue().decode()
size = int(re.search(r'width="(\d+)"', svg).group(1))
d = re.search(r' d="([^"]+)"', svg).group(1)
with open(OUT, "w") as f:
    f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/kofi_qr.py – QR code for {URL} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="200dp" android:height="200dp"
    android:viewportWidth="{size}" android:viewportHeight="{size}">
    <path android:fillColor="#FFFFFF" android:pathData="M0 0h{size}v{size}h-{size}z"/>
    <path android:strokeColor="#000000" android:strokeWidth="1" android:pathData="{d}"/>
</vector>
''')
print("ok", size, "modules incl. border")
